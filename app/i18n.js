  // ---------- форматы ----------
  const UNITS = {
    ru: ['байт', 'КБ', 'МБ', 'ГБ', 'ТБ'], en: ['bytes', 'KB', 'MB', 'GB', 'TB'], de: ['Bytes', 'KB', 'MB', 'GB', 'TB'],
    fr: ['octets', 'Ko', 'Mo', 'Go', 'To'], es: ['bytes', 'KB', 'MB', 'GB', 'TB'],
  }
  const GROUP = { ru: ' ', en: ',', de: '.', fr: ' ', es: '.' }
  const DEC = { ru: ',', en: '.', de: ',', fr: ',', es: ',' }
  const QUOTE = { ru: ['«', '»'], en: ['"', '"'], de: ['»', '«'], fr: ['« ', ' »'], es: ['«', '»'] }
  const FILES = {
    ru: (n) => { const a = n % 10, b = n % 100; return n + ' ' + (a === 1 && b !== 11 ? 'файл' : a >= 2 && a <= 4 && (b < 12 || b > 14) ? 'файла' : 'файлов') },
    en: (n) => n + (n === 1 ? ' file' : ' files'),
    de: (n) => n + (n === 1 ? ' Datei' : ' Dateien'),
    fr: (n) => n + (n <= 1 ? ' fichier' : ' fichiers'),
    es: (n) => n + (n === 1 ? ' archivo' : ' archivos'),
  }

  let lang = 'ru'
  const idx = () => LANGS.indexOf(lang)

  function setLang(l) { lang = LANGS.includes(l) ? l : 'en' }
  function pick(locale) { const l = String(locale || '').slice(0, 2).toLowerCase(); return LANGS.includes(l) ? l : 'en' }

  function t(key, vars) {
    const row = S[key]
    let s = row ? row[idx()] ?? row[1] : key
    if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m))
    return s
  }

  const num = (n) => Math.round(n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, GROUP[lang])
  function bytes(n) {
    if (n == null || isNaN(n)) return '?'
    const u = UNITS[lang]
    let i = 0
    while (n >= 1024 && i < 4) { n /= 1024; i++ }
    if (!i) return num(n) + ' ' + u[0]
    return (n < 100 ? n.toFixed(1) : Math.round(n).toString()).replace('.', DEC[lang]) + ' ' + u[i]
  }
  const two = (n) => String(n).padStart(2, '0')
  function date(ms) {
    if (!ms) return ''
    const d = new Date(ms), dd = two(d.getDate()), mm = two(d.getMonth() + 1), yy = two(d.getFullYear() % 100)
    if (lang === 'en') return `${mm}-${dd}-${yy}`
    if (lang === 'fr' || lang === 'es') return `${dd}/${mm}/${yy}`
    return `${dd}.${mm}.${yy}`
  }
  const q = (s) => QUOTE[lang][0] + s + QUOTE[lang][1]
  const files = (n) => FILES[lang](n)

  const api = { LANGS, NAMES, HELP, setLang, pick, t, num, bytes, date, q, files, get lang() { return lang } }
